/**
 * Countries that have at least `minSpots` spots, sorted by spot count (desc).
 * Used to build the "preferred zone" pickers in onboarding and profile.
 */
export function getZoneCountries(
  minSpots = 3,
  limit?: number,
): { country: string; spots: number }[] {
  const counts: Record<string, number> = {};
  SPOTS.forEach((s) => {
    counts[s.country] = (counts[s.country] || 0) + 1;
  });
  const sorted = Object.entries(counts)
    .filter(([, n]) => n >= minSpots)
    .sort((a, b) => b[1] - a[1])
    .map(([country, n]) => ({ country, spots: n }));
  return limit != null ? sorted.slice(0, limit) : sorted;
}
